const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const page = read('guides/seeking-the-past/index.html');
const js = read('assets/seeking-the-past.js');
const sitemap = read('sitemap.xml');
const achievements = read('achievements/index.html');
const home = read('index.html');
const shells = ['tiel','proxima','gragu','eredrim','smert','lazlo','sariel','genessa'];
const fail = message => { throw new Error(message); };
const expect = (condition, message) => condition || fail(message);
expect(page.includes('name="robots" content="index, follow, max-image-preview:large"'), 'Robots directive is missing');
const title = page.match(/<title>([^<]+)<\/title>/)?.[1] || '';
const description = page.match(/<meta name="description" content="([^"]+)">/)?.[1] || '';
expect(title.length >= 30 && title.length <= 60, `Title length should be 30–60 characters, got ${title.length}`);
expect(description.length >= 120 && description.length <= 165, `Description length should be 120–165 characters, got ${description.length}`);
expect(page.includes('class="seo-breadcrumbs"'), 'Visible breadcrumbs are missing');
expect(page.includes('property="og:image:alt"') && page.includes('name="twitter:image:alt"'), 'Social image descriptions are incomplete');
expect((page.match(/data-memory="[^"]+"/g) || []).length === 40, 'Expected 40 unique Memory checkboxes');
expect(new Set([...page.matchAll(/data-memory="([^"]+)"/g)].map(x => x[1])).size === 40, 'Memory IDs must be unique');
for (const shell of shells) expect(page.includes(`/collectibles/shells/${shell}/`), `Missing ${shell} link`);
expect(page.includes('35/40') && page.includes('39/40'), 'Counter troubleshooting missing');
expect(page.includes('Mether’s Severance') && page.includes('Glimpse Stone'), 'Week 1 economy missing');
expect(page.includes('216 Glimpses') && page.includes('27 Glimpses each'), 'Eight-Shell Glimpse totals are missing');
expect(page.includes('13 Glimpse Stones') && page.includes('2,500 Coin each') && page.includes('5,000 Coin each'), 'Current Merrick stock and prices are missing');
expect(page.includes('community-reported workaround'), 'Community workaround label missing');
expect(js.includes('localStorage') && js.includes('ms2-seeking-the-past-v1'), 'Persistent tracker missing');
expect(js.includes('saved.size') && js.includes('data-complete-shell'), 'Progress and shell completion logic missing');
expect(sitemap.includes('/guides/seeking-the-past/'), 'Sitemap entry missing');
expect(achievements.includes('../guides/seeking-the-past/'), 'Achievement cross-link missing');
expect(home.includes('href="guides/seeking-the-past/"'), 'Homepage must feature the guide');
expect(page.includes('manual browser checklist') && page.includes('does not read your Steam or PlayStation progress'), 'Tracker limitation must be explicit');
expect(page.includes('same active save') && page.includes('cloud-restore branches'), 'Single-save warning is missing');
const schemas = [...page.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
expect(schemas.length === 1, 'Expected one JSON-LD block');
const graph = JSON.parse(schemas[0][1])['@graph'];
expect(graph.some(item => item['@type'] === 'Article' && item.mainEntityOfPage), 'Article schema is incomplete');
expect(graph.find(item => item['@type'] === 'ItemList')?.numberOfItems === 8, 'Eight-Shell ItemList schema is missing');
expect(graph.some(item => item['@type'] === 'BreadcrumbList'), 'Breadcrumb schema is missing');
expect(graph.find(item => item['@type'] === 'FAQPage')?.mainEntity.length === 4, 'FAQ schema must match the four visible questions');
console.log('Seeking the Past validation passed: 8 Shells, 40 Memories, local tracker, current economy, troubleshooting, links and schema.');
